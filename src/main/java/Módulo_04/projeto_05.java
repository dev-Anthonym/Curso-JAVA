package Módulo_04;

public class projeto_05 {
	
	public static void main(String[] args) {
		
		int a, b;
		double resultado;
		
		a = 5;
		b = 2;
		
		resultado = (double) a / b; // O comando "(double)" é para que o resultado da operação de dois números inteiros, saia com a casa decimal certa. Esse comando é chamado de "Casting" que é basicamente a conversão de tipos de dados.
		
		System.out.print(resultado);
	}
}
